# الحد الأدنى المقبول: يفشل التقييم إذا نقصت النتيجة عنه (تراجع في الخوارزمية)
MIN_FOUND = {"GOLD": 18, "GOLD_MORE": 34}


def _adjacent(src, dst):
    (s1, a1), (s2, a2) = (map(int, x.split(":")) for x in (src, dst))
    return s1 == s2 and abs(a1 - a2) == 1


def evaluate(related, gold):
    """يرجع [(المصدر، الهدف، الوصف، المرتبة أو None)]."""
    rows = []
    for src, dst, label in gold:
        ids = [f"{r[0]}:{r[1]}" for r in related.get(src, [])]
        rows.append((src, dst, label, ids.index(dst) + 1 if dst in ids else None))
    return rows


def report(name, rows):
    found = sum(r[3] is not None for r in rows)
    mrr = sum(1 / r[3] for r in rows if r[3]) / len(rows)
    print(f"\n— {name} —")
    for src, dst, label, rank in rows:
        mark = f"✓ المرتبة {rank}" if rank else "✗ غير موجودة"
        print(f"{src:>7} → {dst:<7} {mark:<14} {label}")
    for part, keep in (("في الآية التالية", True), ("في موضع آخر", False)):
        sub = [r for r in rows if _adjacent(r[0], r[1]) == keep]
        if sub:
            print(f"  {part}: {sum(r[3] is not None for r in sub)}/{len(sub)}")
    print(f"النتيجة: {found}/{len(rows)} ضمن أعلى 10 نتائج · متوسط مقلوب المرتبة {mrr:.2f}")
    return found


def main():
    with open(RELATED_FILE, encoding="utf-8") as f:
        related = json.load(f)
    ok = True
    for name, gold in (("GOLD", GOLD), ("GOLD_MORE", GOLD_MORE)):
        found = report(name, evaluate(related, gold))
        if found < MIN_FOUND[name]:
            print(f"تراجع: {found} أقل من الحد الأدنى {MIN_FOUND[name]}")
            ok = False
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main())
